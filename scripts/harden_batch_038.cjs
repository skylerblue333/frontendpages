source = source.replace(/\s*<Button size="sm" variant="outline" onClick=\{\(\) => setOnline\(p => !p\)\}[^>]*>Toggle Offline<\/Button>/, '');
source = source.replace('{online ? "Live" : "Local"}', '"Local only"');
fs.writeFileSync(file, source);
